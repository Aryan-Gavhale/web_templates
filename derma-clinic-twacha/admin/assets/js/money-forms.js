/** Void keeps the receipt and its number; it never deletes. */
export async function voidPayment(pay, onDone) {
  const reason = await confirmModal({
    title: `Void receipt ${pay.receipt_no || `#${pay.id}`}`,
    danger: true,
    confirmLabel: 'Void receipt',
    message: `<strong>${money(pay.amount_paise)}</strong> received on
      ${esc(fmtDate(pay.received_on))} will be marked void. The receipt number stays
      spent and the reason is kept on the record. If it was allocated to an
      instalment, that instalment re-opens.`,
    extra: `<div class="f">
      <label for="v_reason">Reason <span class="req">*</span></label>
      <input id="v_reason" name="reason" type="text" placeholder="e.g. entered twice in error">
      <p class="f__hint">This appears in the audit log and the CSV export.</p>
    </div>`,
  });
  if (!reason) return false;

  try {
    await api(`/admin/payments/${pay.id}/void`, { method: 'POST', body: { reason } });
    toastOk('Receipt voided.');
    await onDone?.();
    return true;
  } catch (err) { reportError(err); return false; }
}

export async function waiveInstalment(inst, onDone) {
  const waiving = inst.status !== 'waived';
  const go = await confirmModal({
    title: waiving ? `Waive instalment ${inst.seq}` : `Reinstate instalment ${inst.seq}`,
    danger: waiving,
    confirmLabel: waiving ? 'Waive it' : 'Reinstate it',
    message: waiving
      ? `<strong>${money(inst.amount_paise)}</strong> due on ${esc(fmtDate(inst.due_date))}
         will stop being counted as owed. Use this for a goodwill write-off, not for
         a payment received — record a receipt for that instead.`
      : `Instalment ${inst.seq} goes back to being due and will count towards
         outstanding again.`,
  });
  if (!go) return false;

  try {
    await api(`/admin/installments/${inst.id}`, { method: 'PATCH', body: { waive: waiving } });
    toastOk(waiving ? 'Instalment waived.' : 'Instalment reinstated.');
    await onDone?.();
    return true;
  } catch (err) { reportError(err); return false; }
}

export async function rescheduleInstalment(inst, onDone) {
  const form = el(`
    <form novalidate>
      <div class="note note--bad" data-form-err hidden></div>
      <div class="f">
        <label for="r_due">New due date <span class="req">*</span></label>
        <input id="r_due" name="due_date" type="date" value="${esc(String(inst.due_date).slice(0, 10))}">
        <p class="f__hint">Only this instalment moves. The rest of the schedule is untouched.</p>
      </div>
      <div class="f">
        <label for="r_note">Note</label>
        <input id="r_note" name="notes" type="text" value="${esc(inst.notes || '')}"
               placeholder="Why it was moved">
      </div>
    </form>`);

  const fields = [{ name: 'due_date', type: 'date' }, { name: 'notes', type: 'text' }];

  const out = await confirmModalWithForm({
    title: `Move instalment ${inst.seq}`,
    form,
    confirmLabel: 'Save new date',
    submit: (body) => api(`/admin/installments/${inst.id}`, { method: 'PATCH', body }),
    fields,
  });

  if (out) { toastOk('Due date updated.'); await onDone?.(); }
  return out;
}

/** Small helper: a modal whose body is a form validated by the server. */
async function confirmModalWithForm({ title, form, confirmLabel, submit, fields }) {
  const { modal } = await import('./core.js');
  return modal({
    title,
    body: form,
    footer: `<button class="btn" data-no>Cancel</button>
             <button class="btn btn--pri" data-yes>${esc(confirmLabel)}</button>`,
    onMount({ close, foot }) {
      foot.querySelector('[data-no]').onclick = () => close(false);
      foot.querySelector('[data-yes]').onclick = (ev) => withBusy(ev.currentTarget, async () => {
        clearErrors(form);
        try {
          await submit(readForm(form, fields));
          close(true);
        } catch (err) {
          if (!showError(form, err)) reportError(err);
        }
      });
    },
  });
}
