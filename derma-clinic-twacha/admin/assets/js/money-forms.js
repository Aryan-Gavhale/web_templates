/* =============================================================================
   Money forms — raise an EMI plan, record a receipt, void a receipt.

   Two rules shape all of this:

   1. The server owns the arithmetic. The plan form previews a schedule by
      asking /emi-plans/preview rather than reproducing the amortisation in the
      browser, so what is shown is exactly what will be written.
   2. Nothing is guessed on the operator's behalf. A payment against an
      instalment is capped at that instalment's balance and the form says what
      the balance is, because a silent over-allocation is a reconciliation
      problem three months later.
   ========================================================================== */

import {
  $, $$, esc, el, api, money, fmtDate, fmtDateShort, fmtAgo, isoToday, debounce,
  drawer, toastOk, reportError, withBusy, on, confirmModal, statusChip, plural,
  PAYMENT_KINDS,
} from './core.js';
import { readForm, showError, clearErrors, renderFields } from './forms.js';

const METHODS = ['upi', 'cash', 'card', 'netbanking', 'neft', 'cheque', 'other'];

/* ============================================================ new plan ==== */

/**
 * @param {object}   o
 * @param {object}   o.patient   { id, name, ref }
 * @param {Array}    [o.services]
 * @param {Function} [o.onDone]
 */
export async function planDrawer({ patient, services, onDone }) {
  const list = services || (await api('/admin/services', { query: { limit: 500 } })).items;

  const fields = [
    { name: 'title', label: 'What the plan is for', type: 'text', required: true,
      placeholder: 'e.g. Laser hair reduction — 6 sessions',
      hint: 'This wording appears on the schedule the patient is given.' },
    { name: 'service_id', label: 'Treatment', type: 'select', blank: '— not linked —',
      options: list.map((s) => ({ value: s.id, label: s.name })),
      hint: 'Optional. Linking it keeps reporting by treatment honest.' },
    { type: 'row', fields: [
      { name: 'principal', label: 'Treatment cost', type: 'money', required: true, placeholder: '120000' },
      { name: 'downpayment', label: 'Down payment', type: 'money', placeholder: '0',
        hint: 'Deducted before the schedule is built.' },
    ] },
    { type: 'row', fields: [
      { name: 'tenure_months', label: 'Tenure (months)', type: 'number', required: true,
        min: 1, max: 60, value: 6 },
      { name: 'interest_rate_bps', label: 'Interest rate', type: 'number', min: 0, max: 5000,
        value: 0, hint: 'In basis points a year. 0 = no-cost. 1200 = 12%.' },
      { name: 'processing_fee', label: 'Processing fee', type: 'money', placeholder: '0' },
    ] },
    { name: 'start_date', label: 'First instalment due on', type: 'date', required: true,
      value: firstOfNextMonth(),
      hint: 'Later instalments fall on the same day of each following month.' },
    { name: 'record_downpayment', label: 'Record the down payment as received now', type: 'checkbox',
      hint: 'Writes a receipt dated today. Leave unticked if it has not been collected.' },
    { name: 'downpayment_method', label: 'Down payment method', type: 'select',
      options: METHODS.map((m) => ({ value: m, label: m.toUpperCase() })), value: 'upi', required: true },
    { name: 'notes', label: 'Internal notes', type: 'textarea', rows: 2 },
  ];

  const form = el(`
    <form novalidate class="stack">
      <div class="note">Raising a plan for <strong>${esc(patient.name)}</strong>
        <span class="mono">${esc(patient.ref || '')}</span>. The schedule below is generated by the
        server in whole paise; the figures you see are the figures that get written.</div>

      <div class="note note--bad" data-form-err hidden></div>

      <div class="card"><div class="card__b">${renderFields(fields, {})}</div></div>

      <div class="card">
        <div class="card__h"><h2>Schedule preview</h2><p>Updates as you type.</p></div>
        <div class="card__b" data-preview>
          <p style="color:var(--mute);font-size:.8rem">Enter a cost and a tenure.</p>
        </div>
      </div>

      <div class="row row--end">
        <button type="button" class="btn" data-cancel>Cancel</button>
        <button type="submit" class="btn btn--pri">Create plan</button>
      </div>
    </form>`);

  const preview = $('[data-preview]', form);

  /* Down-payment method only matters if the down payment is being collected. */
  const methodField = $('[name=downpayment_method]', form).closest('.f');
  const syncMethod = () => {
    methodField.hidden = !$('[name=record_downpayment]', form).checked;
  };
  syncMethod();
  form.addEventListener('change', (e) => {
    if (e.target.name === 'record_downpayment') syncMethod();
  });

  const refreshPreview = debounce(async () => {
    const body = readForm(form, fields);
    if (!body.principal || !body.tenure_months || !body.start_date) return;

    try {
      const out = await api('/admin/emi-plans/preview', { method: 'POST', body });
      preview.innerHTML = previewHtml(out);
    } catch (err) {
      preview.innerHTML = `<p class="note note--warn">${esc(err.message)}</p>`;
    }
  }, 320);

  form.addEventListener('input', refreshPreview);
  form.addEventListener('change', refreshPreview);
  refreshPreview();

  const saved = await drawer({
    title: 'New EMI plan',
    body: form,
    onMount({ close }) {
      $('[data-cancel]', form).onclick = () => close(false);

      form.addEventListener('submit', async (e) => {
        e.preventDefault();
        clearErrors(form);
        await withBusy($('[type=submit]', form), async () => {
          try {
            const out = await api('/admin/emi-plans', {
              method: 'POST',
              body: { ...readForm(form, fields), patient_id: patient.id },
            });
            toastOk(`Plan ${out.ref} created.`);
            close(out);
          } catch (err) {
            if (!showError(form, err)) reportError(err);
          }
        });
      });
    },
  });

  if (saved) await onDone?.(saved);
  return saved;
}

function previewHtml(p) {
  const noCost = p.is_no_cost;
  return `
    <div class="grid grid--3" style="margin-bottom:1rem">
      <div class="kpi" style="box-shadow:none">
        <p class="kpi__k">Monthly instalment</p>
        <p class="kpi__v">${money(p.installment_paise)}</p>
        <p class="kpi__m">${plural(p.rows.length, 'instalment')}</p>
      </div>
      <div class="kpi" style="box-shadow:none">
        <p class="kpi__k">Amount financed</p>
        <p class="kpi__v">${money(p.financed_paise)}</p>
        <p class="kpi__m">${noCost ? 'No interest added' : `${money(p.interest_paise)} interest`}</p>
      </div>
      <div class="kpi" style="box-shadow:none">
        <p class="kpi__k">Total payable</p>
        <p class="kpi__v">${money(p.total_payable_paise)}</p>
        <p class="kpi__m">Across the whole plan</p>
      </div>
    </div>

    ${noCost ? '' : `<p class="note note--warn" style="margin-bottom:1rem">
      This plan carries interest, so the total exceeds the treatment cost by
      <strong>${money(p.interest_paise)}</strong>. Quote the total in writing before the
      patient agrees.</p>`}

    <div class="tw"><table>
      <thead><tr><th style="width:3rem">No.</th><th>Due</th><th class="num">Amount</th></tr></thead>
      <tbody>
        ${p.rows.map((r) => `<tr>
          <td>${r.seq}</td>
          <td style="white-space:nowrap">${esc(fmtDate(r.due_date))}</td>
          <td class="num">${money(r.amount_paise)}</td>
        </tr>`).join('')}
      </tbody>
    </table></div>

    ${p.rounding_note ? `<p style="font-size:.74rem;color:var(--faint);margin-top:.6rem">
      ${esc(p.rounding_note)}</p>` : ''}`;
}

function firstOfNextMonth() {
  const d = new Date();
  d.setMonth(d.getMonth() + 1, 1);
  return d.toLocaleDateString('en-CA');
}

/* ========================================================= new payment ==== */

/**
 * @param {object} o
 * @param {object} o.patient      { id, name, ref }
 * @param {object} [o.plan]       pre-select a plan
 * @param {object} [o.installment] pre-select an instalment (implies its plan)
 */
export async function paymentDrawer({ patient, plan, installment, onDone }) {
  /* The whole patient file is fetched so the instalment picker can show live
     balances rather than making the operator hold them in their head. */
  const file = await api(`/admin/patient-file/${patient.id}`);
  const livePlans = file.plans.filter((p) => ['active', 'defaulted'].includes(p.status));

  const openInstalments = [];
  for (const p of livePlans) {
    const full = await api(`/admin/emi-plans/${p.id}`);
    for (const i of full.installments) {
      if (['due', 'partial'].includes(i.status)) {
        openInstalments.push({ ...i, plan_ref: p.ref, plan_id: p.id, plan_title: p.title });
      }
    }
  }

  const preselect = installment
    ? String(installment.id)
    : (openInstalments.length === 1 ? String(openInstalments[0].id) : '');

  const fields = [
    { name: 'kind', label: 'What is this payment for', type: 'select', required: true,
      options: PAYMENT_KINDS.map(([value, label]) => ({ value, label })),
      value: installment || openInstalments.length ? 'installment' : 'consultation' },

    { name: 'installment_id', label: 'Against instalment', type: 'select', value: preselect,
      blank: '— not tied to an instalment —',
      options: openInstalments.map((i) => ({
        value: i.id,
        label: `${i.plan_ref} · No. ${i.seq} · due ${fmtDateShort(i.due_date)} · ${money(i.outstanding_paise)} owing`,
      })),
      hint: openInstalments.length
        ? 'Choosing one settles it and moves the plan forward automatically.'
        : 'This patient has no open instalments.' },

    { name: 'plan_id', label: 'Against plan', type: 'select', value: plan ? String(plan.id) : '',
      blank: '— not tied to a plan —',
      options: livePlans.map((p) => ({ value: p.id, label: `${p.ref} — ${p.title}` })),
      hint: 'Used when money is received for a plan but not for one specific instalment.' },

    { type: 'row', fields: [
      { name: 'amount', label: 'Amount received', type: 'money', required: true },
      { name: 'received_on', label: 'Date received', type: 'date', required: true, value: isoToday(),
        max: isoToday() },
    ] },

    { type: 'row', fields: [
      { name: 'method', label: 'Method', type: 'select', required: true, value: 'upi',
        options: METHODS.map((m) => ({ value: m, label: m.toUpperCase() })) },
      { name: 'reference', label: 'Reference', type: 'text',
        placeholder: 'UPI ref, cheque no., last 4 digits' },
    ] },

    { name: 'notes', label: 'Notes', type: 'textarea', rows: 2 },
  ];

  const form = el(`
    <form novalidate class="stack">
      <div class="note">Receipt for <strong>${esc(patient.name)}</strong>${
        patient.ref ? ` <span class="mono">${esc(patient.ref)}</span>` : ''}.
        A receipt number is issued on save and cannot be reused.</div>
      <div class="note note--bad" data-form-err hidden></div>
      <div class="card"><div class="card__b">${renderFields(fields, {})}</div></div>
      <div data-balance></div>
      <div class="row row--end">
        <button type="button" class="btn" data-cancel>Cancel</button>
        <button type="submit" class="btn btn--pri">Record receipt</button>
      </div>
    </form>`);

  const instSel = $('[name=installment_id]', form);
  const planSel = $('[name=plan_id]', form);
  const amount = $('[name=amount]', form);
  const balance = $('[data-balance]', form);

  /* Selecting an instalment fixes the plan and offers the exact balance, which
     is what the operator wants nine times out of ten. */
  function syncInstalment({ fillAmount }) {
    const chosen = openInstalments.find((i) => String(i.id) === instSel.value);
    planSel.closest('.f').hidden = !!chosen;

    if (!chosen) { balance.innerHTML = ''; return; }

    planSel.value = String(chosen.plan_id);
    const late = chosen.state === 'overdue';
    balance.innerHTML = `
      <div class="note ${late ? 'note--warn' : ''}">
        Instalment <strong>${chosen.seq}</strong> of ${esc(chosen.plan_ref)} —
        <strong>${money(chosen.outstanding_paise)}</strong> outstanding,
        due ${esc(fmtDate(chosen.due_date))} (${esc(fmtAgo(chosen.due_date))}).
        ${chosen.paid_paise ? `${money(chosen.paid_paise)} already received against it.` : ''}
        <button type="button" class="btn btn--sm" style="margin-top:.5rem" data-fill>
          Use ${money(chosen.outstanding_paise)}
        </button>
      </div>`;

    if (fillAmount) amount.value = (chosen.outstanding_paise / 100).toString();
  }

  instSel.addEventListener('change', () => syncInstalment({ fillAmount: true }));
  on(form, 'click', '[data-fill]', () => syncInstalment({ fillAmount: true }));
  syncInstalment({ fillAmount: !!preselect });

  /* A refund is money leaving, so it should never look like a collection. */
  const kindSel = $('[name=kind]', form);
  kindSel.addEventListener('change', () => {
    const isRefund = kindSel.value === 'refund';
    $('[type=submit]', form).textContent = isRefund ? 'Record refund' : 'Record receipt';
    $('[type=submit]', form).classList.toggle('btn--bad', isRefund);
  });

  const saved = await drawer({
    title: 'Record a payment',
    body: form,
    onMount({ close }) {
      $('[data-cancel]', form).onclick = () => close(false);

      form.addEventListener('submit', async (e) => {
        e.preventDefault();
        clearErrors(form);
        await withBusy($('[type=submit]', form), async () => {
          try {
            const out = await api('/admin/payments', {
              method: 'POST',
              body: { ...readForm(form, fields), patient_id: patient.id },
            });
            toastOk(`${out.amount_display} recorded — receipt ${out.receipt_no}.`);
            close(out);
          } catch (err) {
            if (!showError(form, err)) reportError(err);
          }
        });
      });
    },
  });

  if (saved) await onDone?.(saved);
  return saved;
}

